/**
 * Emits an idempotent upsert of every bundled location and tide station.
 *
 * The Supabase `locations` table is not decoration: `refresh-conditions`
 * derives the station list it polls from it, and `readConditions()` looks a
 * location up by slug there before it will return any snapshot. So a location
 * that exists in `src/data/locations.ts` but not in that table has no live
 * tide and no live forecast, silently — the card just says "updated unknown".
 *
 * The guide grew from 15 spots to 25 without the table following, which is
 * exactly how that happened. Generating the seed from the bundled data means
 * the two cannot disagree about anything a human had to retype.
 *
 *   npx vite-node scripts/gen-location-seed.mjs > supabase/migrations/<ts>_sync_locations.sql
 */
import { LOCATIONS } from '../src/data/locations.ts';

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `ARRAY[${(a ?? []).map(q).join(',')}]::text[]`;

const stations = new Map();
for (const l of LOCATIONS) {
  const s = l.tide_station;
  if (s?.noaa_id && !stations.has(s.noaa_id)) stations.set(s.noaa_id, s);
}

for (const l of LOCATIONS) {
  if (!l.tide_station?.noaa_id) {
    throw new Error(`No noaa_id for ${l.slug}. Refusing to emit a seed that would null a live station link.`);
  }
}

const out = [];
out.push(`-- Sync the locations/tide_stations tables with the bundled guide data.
--
-- Generated by scripts/gen-location-seed.mjs — do not hand-edit; regenerate.
--
-- Why this exists: refresh-conditions polls whatever stations the locations
-- table names, and readConditions() refuses to return a snapshot for a slug
-- that is not in it. The guide expanded from 15 spots to 25 and the table did
-- not follow, so ten spots — St. Pete Pier, Skyway North, both Fort De Soto
-- piers, Egmont Key, Weedon Island, Pass-a-Grille, Bunces Pass, New Pass and
-- South Lido — had no live tide at all, and six NOAA stations were never
-- polled. Nothing errored; the cards just read "updated unknown".
--
-- Idempotent: safe to re-run, and safe to run against the current 15 rows.

begin;
`);

out.push(`-- ${stations.size} NOAA CO-OPS stations`);
for (const s of stations.values()) {
  out.push(
    `insert into public.tide_stations (id, name, url) values (${q(s.noaa_id)}, ${q(s.name ?? s.noaa_id)}, ${q(s.url ?? null)})\n` +
      `  on conflict (id) do update set name = excluded.name, url = excluded.url;`,
  );
}

out.push(`\n-- ${LOCATIONS.length} locations`);
for (const l of LOCATIONS) {
  out.push(
    `insert into public.locations (slug, name, region, lat, lng, access, structures, tide_station_id)\n` +
      `  values (${q(l.slug)}, ${q(l.name)}, ${q(l.region)}, ${l.lat}, ${l.lng}, ` +
      `${q((l.access ?? []).join(', '))}, ${arr(l.structures)}, ${q(l.tide_station?.noaa_id)})\n` +
      `  on conflict (slug) do update set\n` +
      `    name = excluded.name, region = excluded.region, lat = excluded.lat, lng = excluded.lng,\n` +
      `    access = excluded.access, structures = excluded.structures,\n` +
      `    tide_station_id = excluded.tide_station_id;`,
  );
}

out.push(`\ncommit;`);
console.log(out.join('\n'));
